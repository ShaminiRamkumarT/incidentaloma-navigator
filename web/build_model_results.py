"""Runs the trained model over the held-out synthetic reports and writes web/model_results.js
for the "Multi-organ" tab of the browser demo (the model itself runs in Python, not in the browser).

Usage:  python web/build_model_results.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from navigator import extract_ml  # noqa: E402
from navigator.guidelines import classify, concordance  # noqa: E402
from navigator.schema import Finding  # noqa: E402

SKIP = {"organ", "side", "size_cm", "modality", "stated_actions"}


def main():
    reports = json.loads((ROOT / "data" / "synthetic_test.json").read_text())
    summary = json.loads((ROOT / "results" / "summary_ml_synth_test.json").read_text())
    out = []
    for r in reports:
        gold = {(x["gold"]["organ"], x["gold"].get("side", "unknown")): x for x in r["findings"]}
        rows = []
        for f in extract_ml.extract(r["text"]).findings:
            g, c = classify(f), concordance(f, classify(f))
            gx = gold.get((f.organ, f.side))
            gc = None
            if gx:
                gf = Finding(**gx["gold"])
                gc = concordance(gf, classify(gf)).status
            fields = {k: v for k, v in f.model_dump(mode="json").items()
                      if k not in SKIP and v not in (None, False, "unknown", "indeterminate", [])}
            rows.append({"organ": f.organ, "side": f.side, "size_cm": f.size_cm, "modality": f.modality,
                         "category": g.category, "actions": [a.value for a in g.actions],
                         "stated": [a.value for a in f.stated_actions], "status": c.status, "severity": c.severity,
                         "message": c.message, "rationale": g.rationale, "source": g.source, "notes": g.notes,
                         "fields": fields, "gold_category": gx["expected_category"] if gx else None,
                         "gold_status": gc})
        out.append({"id": r["id"], "text": r["text"], "findings": rows})
    js = ("// Generated by web/build_model_results.py from data/synthetic_test.json - do not edit by hand.\n"
          f"window.MODEL_RESULTS = {json.dumps(out)};\nwindow.MODEL_SUMMARY = {json.dumps(summary)};\n")
    (ROOT / "web" / "model_results.js").write_text(js)
    print(f"{len(out)} reports, {sum(len(x['findings']) for x in out)} findings -> web/model_results.js")


if __name__ == "__main__":
    main()
